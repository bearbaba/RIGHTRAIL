// Verifies a *separately deployed* RightsAccessGate transaction. Unsigned; public on-chain reads only.
import {createClient} from 'genlayer-stable';
import {studionet} from 'genlayer-stable/chains';
import {TransactionHashVariant} from 'genlayer-stable/types';
import {createHash} from 'node:crypto';
const HASH=process.env.RIGHTRAIL_GATE_TX_HASH?.trim();
const RIGHTS='0xef37288aB08A30697841C4fFe93C1D71E23C464b';
if(!/^0x[0-9a-fA-F]{64}$/.test(HASH||''))throw Error('Pass the real Access Gate deployment hash as RIGHTRAIL_GATE_TX_HASH. RightsRail deployment tx is NOT a Gate tx.');
const client=createClient({chain:studionet});
const tx=await client.getTransaction({hash:HASH});
if(!tx)throw Error('Transaction not found');
const status=String(tx.statusName??tx.status_name??tx.status??'UNKNOWN').toUpperCase();
const explicit=String(tx.txExecutionResultName??'');
const receipts=tx.consensus_data?.leader_receipt??tx.consensusData?.leaderReceipt??[];
if(status!=='FINALIZED')throw Error('Deployment not FINALIZED: '+status);
if(explicit==='FINISHED_WITH_ERROR')throw Error('GenVM execution failed');
const address=tx.data?.contract_address??tx.data?.contractAddress??tx.contract_address??tx.contractAddress;
if(!/^0x[0-9a-fA-F]{40}$/.test(address||''))throw Error('No deployed contract_address in transaction data');
if(address.toLowerCase()===RIGHTS.toLowerCase())throw Error('This is the existing RightsRail deployment, NOT RightsAccessGate. Submit a DIFFERENT Gate deployment transaction.');
const code=await client.getContractCode(address);
if(typeof code!=='string'||!code.includes('class RightsAccessGate(gl.Contract)'))throw Error('Deployed code is not RightsAccessGate; do not use as Gate address');
const schema=await client.getContractSchema(address);
const methods=Object.keys(schema?.methods??{});
for(const m of ['can_access','record_access','receipt_for','has_access_receipt','stats'])if(!methods.includes(m))throw Error('Missing '+m+' method');
const raw=await client.readContract({address,functionName:'stats',args:[],transactionHashVariant:TransactionHashVariant.LATEST_FINAL});
const stats=typeof raw==='string'?JSON.parse(raw):raw;
if(String(stats.rights_address??'').toLowerCase()!==RIGHTS.toLowerCase())throw Error('Gate constructor points to wrong RightsRail address: '+JSON.stringify(stats));
if(Number(stats.receipts)!==0)throw Error('Unexpected nonzero receipts on a new Gate');
console.log(JSON.stringify({verified:true,chainId:61999,transactionHash:HASH,gateAddress:address,rightsAddress:stats.rights_address,finalizedStats:stats,methods,deployedSha256:createHash('sha256').update(code).digest('hex')},null,2));
